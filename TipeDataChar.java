public class TipeDataChar {
    public static void main(String[] args) {

        char e = 'E';
        char l = 'L';
        char m = 'M';
        char a = 'A';
        char n = 'N';

        // untuk menyetak sebuah variabel dengan "println" akan membuat sebuah enter
        // baru
        // tetapi jika tidak menggunakan "ln" pada "println" jadi "print" akan
        // membuatnya menjadi 1 line saja
        // tidak membuat line baru atau enter
        System.out.print(e);
        System.out.print(l);
        System.out.print(m);
        System.out.print(a);
        System.out.println(n);

        // ini secara manual ketika diterminal
        // ketika ada perubahan dan ingin printout menggunakan command prompt di
        // terminal harustesting ulang dan dari awal lagi contoh file ini
        // pertama "javac <Nama File.java>"
        // kedua akan membuat class baru dengan nama file yang sama
        // ketiga "java <Nama File / Nama Class>"
        // keempat akan menghasilkan data value yang baru

        // Jika secara langsung tinggal klik kanan pada file lalu run saja
    }

}
